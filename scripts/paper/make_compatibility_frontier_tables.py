"""Supplementary Tables for Supplementary Note S5: the ELES compatibility frontier, from its CSV.

Writes the two tabular bodies (coverage and accuracy, then screening) to results/tables/compatibility_frontier.tex. The
captions live in the manuscript; the generated block is inlined there between begin/end markers, like the figures.

Run from the repository root:
    uv run python scripts/paper/make_compatibility_frontier_tables.py
"""

from __future__ import annotations

from pathlib import Path
from typing import Final

import pandas as pd

PROJECT_DIR: Final[Path] = Path(__file__).resolve().parents[2]
INPUT_PATH: Final[Path] = PROJECT_DIR / "results" / "data" / "eles_compatibility_frontier.csv"
OUTPUT_PATH: Final[Path] = PROJECT_DIR / "results" / "tables" / "compatibility_frontier.tex"

# Loosest to strictest, as in the Methods.
LABELS: Final[dict[str, str]] = {
    "no_filter": "No filter",
    "domestic_only": "Slovenian only",
    "hamming_32": "$h \\le 32$",
    "hamming_16": "$h \\le 16$",
    "hamming_8": "$h \\le 8$",
    "hamming_4": "$h \\le 4$",
    "hamming_2": "$h \\le 2$",
    "hamming_1": "$h \\le 1$",
    "exact_lines": "Exact (deployed)",
    "all_switching": "All switching flags",
}
AVAILABILITY: Final[tuple[str, str]] = ("retrospective", "causal_lag0")


def _pct(x: float) -> str:
    return f"{100 * x:.2f}"


def _ms(x: float) -> str:
    return "0" if x == 0 else f"{1000 * x:+.1f}".replace("-", "$-$")


def _pair(df: pd.DataFrame, rule: str, column: str, fmt) -> list[str]:
    return [fmt(df.loc[(rule, a), column]) for a in AVAILABILITY]


def _tabular(header: str, rows: list[str], n_numeric: int) -> str:
    return "\n".join(
        [
            f"\\begin{{tabular}}{{l{'r' * n_numeric}}}",
            "\\toprule",
            header,
            "\\midrule",
            *rows,
            "\\bottomrule",
            "\\end{tabular}",
        ]
    )


def render(df: pd.DataFrame) -> str:
    df = df.set_index(["rule", "availability"])
    if set(df.index.get_level_values(0)) != set(LABELS):
        raise ValueError(f"rules in {INPUT_PATH.name} do not match LABELS")

    coverage_rows, screening_rows = [], []
    for rule, label in LABELS.items():
        mean_pool = df.loc[(rule, AVAILABILITY[0]), "mean_candidate_pool_retrospective"]
        pools = f"{mean_pool:,.0f}" if mean_pool >= 100 else f"{mean_pool:.1f}"
        cells = [
            pools,
            *_pair(df, rule, "record_coverage", _pct),
            *_pair(df, rule, "state_coverage_complete", _pct),
            *_pair(df, rule, "paired_mae_minus_exact", _ms),
            *_pair(df, rule, "share_neighbours_line_mismatch", _pct),
        ]
        coverage_rows.append(" & ".join([label, *cells]) + " \\\\")
        cells = []
        for tau in ("150ms", "200ms"):
            cells += _pair(df, rule, f"referral_load_{tau}", _pct)
            cells += _pair(df, rule, f"missed_unsafe_{tau}", lambda x: f"{int(x):,}")
        screening_rows.append(" & ".join([label, *cells]) + " \\\\")

    rc = "Retro. & Causal"
    coverage = _tabular(
        "& & \\multicolumn{2}{c}{Records covered (\\%)} & \\multicolumn{2}{c}{Complete states (\\%)} "
        "& \\multicolumn{2}{c}{$\\Delta$MAE (ms)} & \\multicolumn{2}{c}{Other lines (\\%)} \\\\\n"
        "\\cmidrule(lr){3-4}\\cmidrule(lr){5-6}\\cmidrule(lr){7-8}\\cmidrule(lr){9-10}\n"
        f"Definition & Candidates & {rc} & {rc} & {rc} & {rc} \\\\",
        coverage_rows,
        9,
    )
    screening = _tabular(
        "& \\multicolumn{4}{c}{$\\tau = \\qty{150}{\\ms}$} & \\multicolumn{4}{c}{$\\tau = \\qty{200}{\\ms}$} \\\\\n"
        "\\cmidrule(lr){2-5}\\cmidrule(lr){6-9}\n"
        "& \\multicolumn{2}{c}{Referral load (\\%)} & \\multicolumn{2}{c}{Missed unsafe} "
        "& \\multicolumn{2}{c}{Referral load (\\%)} & \\multicolumn{2}{c}{Missed unsafe} \\\\\n"
        "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}\\cmidrule(lr){8-9}\n"
        f"Definition & {rc} & {rc} & {rc} & {rc} \\\\",
        screening_rows,
        8,
    )
    note = "% Generated by scripts/paper/make_compatibility_frontier_tables.py -- do not edit by hand."
    return f"{note}\n% coverage and accuracy\n{coverage}\n% screening\n{screening}\n"


def main() -> None:
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(render(pd.read_csv(INPUT_PATH)))
    print(f"Saved {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
