"""Supplementary Note S6: screening reliability tables and the threshold-curve figure, from their CSVs.

Writes results/tables/screening_reliability.tex (five tabular bodies, each after a "% <name>" marker: policies,
calibration, matched, missed, costs) and results/figures/threshold_curve.tex. Captions live in the manuscript; the
generated blocks are inlined there between begin/end markers, like the other supplementary tables.

Run from the repository root:
    uv run python scripts/paper/make_screening_reliability_supplement.py
"""

from __future__ import annotations

import math
from pathlib import Path
from typing import Final

import pandas as pd

PROJECT_DIR: Final[Path] = Path(__file__).resolve().parents[2]
DATA_DIR: Final[Path] = PROJECT_DIR / "results" / "data"
RELIABILITY: Final[Path] = DATA_DIR / "screening_reliability.csv"
CURVE: Final[Path] = DATA_DIR / "screening_threshold_curve.csv"
MISSED: Final[Path] = DATA_DIR / "screening_missed_unsafe.csv"
TABLES_PATH: Final[Path] = PROJECT_DIR / "results" / "tables" / "screening_reliability.tex"
FIGURE_PATH: Final[Path] = PROJECT_DIR / "results" / "figures" / "threshold_curve.tex"

ARMS: Final[tuple[tuple[str, str, str], ...]] = (
    ("BUS39", "retrospective", "BUS39"),
    ("ELES", "retrospective", "ELES retro."),
    ("ELES", "causal_lag0", "ELES causal"),
)
TAUS: Final[tuple[float, ...]] = (0.15, 0.20)
PRIMARY_ALPHA: Final[float] = 0.01
NOTE: Final[str] = "% Generated by scripts/paper/make_screening_reliability_supplement.py -- do not edit by hand."


def _tabular(spec: str, header: list[str], rows: list[str]) -> str:
    return "\n".join(
        [f"\\begin{{tabular}}{{{spec}}}", "\\toprule", *header, "\\midrule", *rows, "\\bottomrule", "\\end{tabular}"]
    )


def _pct(x: float, digits: int = 2) -> str:
    return f"{100 * x:.{digits}f}"


def _int(x: float) -> str:
    return f"{int(round(x)):,}"


def _signed(x: float) -> str:
    return "0" if x == 0 else f"{x:+.0f}".replace("-", "$-$")


def _tau_label(tau: float) -> str:
    return f"$\\tau = \\qty{{{round(1000 * tau)}}}{{\\ms}}$"


class Data:
    def __init__(self) -> None:
        self.d = pd.read_csv(RELIABILITY)

    def point(self, dataset: str, availability: str, **where: object) -> float:
        d = self.d[(self.d["dataset"] == dataset) & (self.d["availability"] == availability)]
        for col, val in where.items():
            d = d[d[col].isna()] if val is None else d[d[col] == val]
        d = d[d["resampling_unit"].isna() | (d["resampling_unit"] == "state")]
        if len(d) != 1:
            raise ValueError(f"{dataset} {availability} {where}: {len(d)} rows")
        return float(d["estimate"].iloc[0])

    def widest(self, dataset: str, availability: str, tau: float, quantity: str) -> pd.Series:
        d = self.d[
            (self.d["dataset"] == dataset)
            & (self.d["availability"] == availability)
            & (self.d["analysis"] == "Q2")
            & (self.d["tau_s"] == tau)
            & (self.d["quantity"] == quantity)
            & (self.d["decides"] == True)  # noqa: E712
        ]
        return d.loc[(d["ci_high"] - d["ci_low"]).idxmax()]


def policies_table(data: Data) -> str:
    """Referral load and missed unsafe states per policy, both thresholds."""
    rows: list[str] = []
    for tau in TAUS:
        rows.append(f"\\multicolumn{{7}}{{l}}{{{_tau_label(tau)}}} \\\\")
        lines: list[tuple[str, dict[str, object], str, str]] = [
            ("Unmodified screen", {"analysis": "Q1", "policy": "P0"}, "referral_load", "missed_unsafe")
        ]
        for m in (0.01, 0.02, 0.03, 0.05):
            lines.append(
                (
                    f"Fixed margin, \\qty{{{round(1000 * m)}}}{{\\ms}}",
                    {"analysis": "Q4", "policy": "P1", "param": m},
                    "referral_load",
                    "missed_unsafe",
                )
            )
        for a in (0.05, 0.02, 0.01, 0.005):
            lines.append(
                (
                    f"Constant margin, $\\alpha = {100 * a:g}\\%$",
                    {"analysis": "Q1", "policy": "P2", "alpha": a},
                    "referral_load",
                    "missed_unsafe",
                )
            )
        lines.append(
            (
                f"Scaled margin, $\\alpha = {100 * PRIMARY_ALPHA:g}\\%$",
                {"analysis": "Q1", "policy": "P3", "alpha": PRIMARY_ALPHA},
                "referral_load",
                "missed_unsafe",
            )
        )
        lines.append(
            (
                "Distance rejection, matched",
                {"analysis": "Q2", "policy": "matched"},
                "referral_load_P4_matched",
                "missed_unsafe_P4_matched",
            )
        )
        for label, where, load_q, miss_q in lines:
            cells = []
            for dataset, availability, _ in ARMS:
                cells.append(_pct(data.point(dataset, availability, tau_s=tau, quantity=load_q, **where)))
                cells.append(_int(data.point(dataset, availability, tau_s=tau, quantity=miss_q, **where)))
            rows.append(" & ".join([f"\\quad {label}", *cells]) + " \\\\")
    header = [
        " & " + " & ".join(f"\\multicolumn{{2}}{{c}}{{{name}}}" for _, _, name in ARMS) + " \\\\",
        "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}",
        "Policy" + " & Load (\\%) & Missed" * len(ARMS) + " \\\\",
    ]
    return _tabular("lrrrrrr", header, rows)


def calibration_table(data: Data) -> str:
    """Constant conformal margin per alpha: median margin, exceedance rate, burn-in."""
    rows = []
    for a in (0.05, 0.02, 0.01, 0.005):
        cells = [f"{100 * a:g}"]
        for dataset, availability, _ in ARMS:
            q = {"analysis": "margin", "policy": "P2", "alpha": a}
            cells.append(f"{1000 * data.point(dataset, availability, quantity='median_margin_s', **q):.0f}")
            cells.append(_pct(data.point(dataset, availability, quantity="exceedance_rate", **q)))
        cells.append(
            _int(
                data.point(
                    "ELES",
                    "causal_lag0",
                    quantity="states_without_finite_margin",
                    analysis="margin",
                    policy="P2",
                    alpha=a,
                )
            )
        )
        rows.append(" & ".join(cells) + " \\\\")
    header = [
        " & " + " & ".join(f"\\multicolumn{{2}}{{c}}{{{name}}}" for _, _, name in ARMS) + " & \\\\",
        "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(lr){6-8}",
        "$\\alpha$ (\\%)" + " & Margin (ms) & Exceeded (\\%)" * len(ARMS) + " & Burn-in \\\\",
    ]
    return _tabular("rrrrrrrr", header, rows)


def matched_table(data: Data) -> str:
    """Q2: missed unsafe states at the constant margin's load, differences with intervals."""
    rows = []
    for dataset, availability, name in ARMS:
        for tau in TAUS:
            q = {"analysis": "Q2", "policy": "matched", "tau_s": tau}
            cells = [
                name,
                f"{round(1000 * tau)}",
                _pct(data.point(dataset, availability, quantity="referral_load_P2", **q)),
            ]
            cells.append(_int(data.point(dataset, availability, quantity="missed_unsafe_P2", **q)))
            for quantity in ("missed_P3_matched_minus_P2", "missed_P4_matched_minus_P2"):
                w = data.widest(dataset, availability, tau, quantity)
                cells.append(f"{_signed(w['estimate'])} ({_signed(w['ci_low'])}, {_signed(w['ci_high'])})")
            rows.append(" & ".join(cells) + " \\\\")
    header = [
        "& $\\tau$ (ms) & Load (\\%) & Missed, constant & Scaled $-$ constant & Distance $-$ constant \\\\",
    ]
    return _tabular("lrrrrr", header, rows)


def missed_table() -> str:
    """Q3: the states the unmodified screen misses."""
    m = pd.read_csv(MISSED)
    rows = []
    for dataset, availability, name in ARMS:
        for tau in TAUS:
            r = m[(m["dataset"] == dataset) & (m["availability"] == availability) & (m["tau_s"] == tau)].iloc[0]
            cells = [
                name,
                f"{round(1000 * tau)}",
                _int(r["n_unsafe"]),
                _int(r["n_missed"]),
                _int(r["n_missed_within_label_resolution"]),
                f"{1000 * r['depth_s_q50']:.0f}",
                f"{1000 * r['passed_by_s_q50']:.1f}",
                _int(r["n_missed_with_true_generator_selected"]),
                f"{_int(r['n_missed_locations'])} ({_pct(r['largest_location_share'], 0)})",
                f"{r['distance_percentile_median']:.2f}",
            ]
            rows.append(" & ".join(cells) + " \\\\")
    header = [
        "& $\\tau$ & & & Within & Depth & Passed by & True gen. & Locations & Distance \\\\",
        "& (ms) & Unsafe & Missed & 10 ms & (ms) & (ms) & selected & (largest \\%) & percentile \\\\",
    ]
    return _tabular("lrrrrrrrrr", header, rows)


def costs_table(data: Data) -> str:
    """Q5: the miss-to-referral cost ratio below which each policy is cheaper than referring every state."""
    lines: list[tuple[str, dict[str, object]]] = [("Unmodified screen", {"policy": "P0"})]
    lines += [
        (f"Fixed margin, \\qty{{{round(1000 * m)}}}{{\\ms}}", {"policy": f"P1_m{m:g}"})
        for m in (0.01, 0.02, 0.03, 0.05)
    ]
    lines += [(f"Constant margin, $\\alpha = {100 * a:g}\\%$", {"policy": f"P2_a{a:g}"}) for a in (0.05, 0.01)]
    lines += [("Distance rejection, matched", {"policy": "P4_matched"})]
    rows = []
    for label, where in lines:
        cells = []
        for dataset, availability, _ in ARMS:
            for tau in TAUS:
                v = data.point(
                    dataset, availability, analysis="Q5", tau_s=tau, quantity="break_even_cost_ratio", **where
                )
                cells.append("$\\infty$" if math.isinf(v) else f"{v:,.0f}")
        rows.append(" & ".join([label, *cells]) + " \\\\")
    header = [
        " & " + " & ".join(f"\\multicolumn{{2}}{{c}}{{{name}}}" for _, _, name in ARMS) + " \\\\",
        "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}",
        "Policy" + " & 150 & 200" * len(ARMS) + " \\\\",
    ]
    return _tabular("lrrrrrr", header, rows)


