"""Supplementary Note S7 tables: headline ELES intervals under every resampling unit, and the label-step shift.

Writes results/tables/clustered_intervals.tex (two tabular bodies after the markers "% intervals" and "% label_steps")
from results/data/clustered_intervals.csv and results/data/label_step_perturbation.csv. Captions live in the
manuscript; the blocks are inlined there between begin/end markers.

Run from the repository root:
    uv run python scripts/paper/make_clustered_intervals_tables.py
"""

from __future__ import annotations

from pathlib import Path
from typing import Final

import pandas as pd

PROJECT_DIR: Final[Path] = Path(__file__).resolve().parents[2]
DATA_DIR: Final[Path] = PROJECT_DIR / "results" / "data"
OUTPUT_PATH: Final[Path] = PROJECT_DIR / "results" / "tables" / "clustered_intervals.tex"
NOTE: Final[str] = "% Generated by scripts/paper/make_clustered_intervals_tables.py -- do not edit by hand."
UNITS: Final[tuple[str, ...]] = ("state", "topology_group", "calendar_day", "calendar_week")

# (analysis, quantity, label, scale, decimals): scale converts to the printed unit.
ROWS: Final[tuple[tuple[str, str, str, float, int], ...]] = (
    ("H1", "recall_150ms", "Recall, \\qty{150}{\\ms} (\\%)", 100, 2),
    ("H1", "recall_200ms", "Recall, \\qty{200}{\\ms} (\\%)", 100, 2),
    ("H1", "false_alarm_100ms", "False alarm, \\qty{100}{\\ms} (\\%)", 100, 2),
    ("H1", "false_alarm_150ms", "False alarm, \\qty{150}{\\ms} (\\%)", 100, 2),
    ("H1", "false_alarm_200ms", "False alarm, \\qty{200}{\\ms} (\\%)", 100, 2),
    ("H1", "referral_100ms", "State referral, \\qty{100}{\\ms} (\\%)", 100, 2),
    ("H1", "referral_150ms", "State referral, \\qty{150}{\\ms} (\\%)", 100, 2),
    ("H1", "referral_200ms", "State referral, \\qty{200}{\\ms} (\\%)", 100, 2),
    ("H2", "mae_oracle", "MAE, recorded generator (s)", 1, 4),
    ("H2", "mae_generator_only_selection", "MAE, highest-support generator (s)", 1, 4),
    ("H3", "mae_retrieval_minus_gradient_boosting", "MAE, retrieval $-$ gradient boosting (s)", 1, 4),
    ("H4", "mae_causal_minus_retrospective", "MAE, causal $-$ retrospective (s)", 1, 4),
    ("H6", "recall_retrieval_minus_gradient_boosting", "Recall at matched load, retrieval $-$ GB (pts)", 100, 2),
    ("H5", "naurc_cct_weighted_std_common", "nAURC, weighted CCT dispersion", 1, 3),
    ("H5", "naurc_n_neighbors_common", "nAURC, retrieved neighbor count", 1, 3),
    ("H5", "naurc_n_unique_states_common", "nAURC, unique supporting states", 1, 3),
    ("H5", "naurc_location_weight_mass_common", "nAURC, location support mass", 1, 3),
    ("H5", "naurc_n_eff_common", "nAURC, effective sample size", 1, 3),
    ("H5", "naurc_distance_min_common", "nAURC, minimum query distance", 1, 3),
    ("H5", "naurc_neighborhood_compactness_common", "nAURC, neighborhood compactness", 1, 3),
    ("H5", "naurc_n_neighbors_all_covered", "nAURC, neighbor count, all covered", 1, 3),
    ("H5", "naurc_n_unique_states_all_covered", "nAURC, unique states, all covered", 1, 3),
)


def _num(x: float, decimals: int) -> str:
    return f"{x:.{decimals}f}".replace("-", "$-$")


def _tabular(spec: str, header: list[str], rows: list[str]) -> str:
    return "\n".join(
        [f"\\begin{{tabular}}{{{spec}}}", "\\toprule", *header, "\\midrule", *rows, "\\bottomrule", "\\end{tabular}"]
    )


def intervals() -> str:
    d = pd.read_csv(DATA_DIR / "clustered_intervals.csv").set_index(["analysis", "quantity", "resampling_unit"])
    rows = []
    for analysis, quantity, label, scale, dec in ROWS:
        cells = [label, _num(scale * d.loc[(analysis, quantity, "state"), "estimate"], dec)]
        for unit in UNITS:
            r = d.loc[(analysis, quantity, unit)]
            cells.append(f"{_num(scale * r['ci_low'], dec)}, {_num(scale * r['ci_high'], dec)}")
        rows.append(" & ".join(cells) + " \\\\")
    header = ["Quantity & Estimate & State & Topology group & Calendar day & Calendar week \\\\"]
    return _tabular("lrrrrr", header, rows)


def label_steps() -> str:
    d = pd.read_csv(DATA_DIR / "label_step_perturbation.csv")
    d = d[d["resampling_unit"].isna() | (d["resampling_unit"] == "state")].set_index(
        ["dataset", "availability", "tau_s", "quantity"]
    )["estimate"]
    arms = (
        ("BUS39", "retrospective", "BUS39"),
        ("ELES", "retrospective", "ELES retro."),
        ("ELES", "causal_lag0", "ELES causal"),
    )
    rows = []
    for ds, av, name in arms:
        for tau in (0.15, 0.20):
            k = (ds, av, tau)
            cells = [
                name,
                f"{round(1000 * tau)}",
                f"{int(d[(*k, 'n_boundary_states')]):,} ({int(d[(*k, 'n_boundary_states_referred')]):,})",
                *(f"{int(d[(*k, f'n_unsafe_shift{s:+d}')]):,}" for s in (-1, 0, 1)),
                *(f"{int(d[(*k, f'missed_unsafe_shift{s:+d}')]):,}" for s in (-1, 0, 1)),
                *(f"{100 * d[(*k, f'recall_shift{s:+d}')]:.1f}" for s in (-1, 0, 1)),
            ]
            rows.append(" & ".join(cells) + " \\\\")
    header = [
        "& & & \\multicolumn{3}{c}{Unsafe} & \\multicolumn{3}{c}{Missed unsafe} & \\multicolumn{3}{c}{Recall (\\%)} \\\\",
        "\\cmidrule(lr){4-6}\\cmidrule(lr){7-9}\\cmidrule(lr){10-12}",
        "& $\\tau$ (ms) & Boundary (referred)" + " & $-1$ & 0 & $+1$" * 3 + " \\\\",
    ]
    return _tabular("lrr" + "r" * 9, header, rows)


def main() -> None:
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(f"{NOTE}\n% intervals\n{intervals()}\n% label_steps\n{label_steps()}\n")
    print(OUTPUT_PATH.read_text())


if __name__ == "__main__":
    main()
