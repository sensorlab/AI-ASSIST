def _num(x: float, decimals: int) -> str:
    return f"{x:.{decimals}f}".replace("-", "$-$")


def _tabular(spec: str, header: list[str], rows: list[str]) -> str:
    return "\n".join(
        [f"\\begin{{tabular}}{{{spec}}}", "\\toprule", *header, "\\midrule", *rows, "\\bottomrule", "\\end{tabular}"]
    )


def intervals() -> str:
    d = pd.read_csv(DATA_DIR / "clustered_intervals.csv").set_index(["analysis", "quantity", "resampling_unit"])
    rows = []
    for analysis, quantity, label, scale, dec in ROWS:
        cells = [label, _num(scale * d.loc[(analysis, quantity, "state"), "estimate"], dec)]
        for unit in UNITS:
            r = d.loc[(analysis, quantity, unit)]
            cells.append(f"{_num(scale * r['ci_low'], dec)}, {_num(scale * r['ci_high'], dec)}")
        rows.append(" & ".join(cells) + " \\\\")
    header = ["Quantity & Estimate & State & Topology group & Calendar day & Calendar week \\\\"]
    return _tabular("lrrrrr", header, rows)


def later() -> str:
    """Second panel: the later headline intervals, each required under all four units."""
    rows = []
    for csv, where, quantity, label, scale, dec in LATER_ROWS:
        d = pd.read_csv(DATA_DIR / f"{csv}.csv")
        for col, value in where.items():
            d = d[d[col] == value]
        d = d[d["quantity"] == quantity].set_index("resampling_unit")
        if not set(UNITS) <= set(d.index) or d.index.duplicated().any():
            raise ValueError(f"{csv}: {quantity} lacks a unique row for every unit: {list(d.index)}")
        cells = [label, _num(scale * d.loc["state", "estimate"], dec)]
        cells += [f"{_num(scale * d.loc[u, 'ci_low'], dec)}, {_num(scale * d.loc[u, 'ci_high'], dec)}" for u in UNITS]
        rows.append(" & ".join(cells) + " \\\\")
    header = ["Quantity & Estimate & State & Topology group & Calendar day & Calendar week \\\\"]
    return _tabular("lrrrrr", header, rows)


def label_steps() -> str:
    d = pd.read_csv(DATA_DIR / "label_step_perturbation.csv")
    d = d[d["resampling_unit"].isna() | (d["resampling_unit"] == "state")].set_index(
        ["dataset", "availability", "tau_s", "quantity"]
    )["estimate"]
    arms = (
        ("BUS39", "retrospective", "BUS39"),
        ("ELES", "retrospective", "ELES retro."),
        ("ELES", "causal_lag0", "ELES causal"),
    )
    rows = []
    for ds, av, name in arms:
        for tau in (0.15, 0.20):
            k = (ds, av, tau)
            cells = [
                name,
                f"{round(1000 * tau)}",
                f"{int(d[(*k, 'n_boundary_states')]):,} ({int(d[(*k, 'n_boundary_states_referred')]):,})",
                *(f"{int(d[(*k, f'n_unsafe_shift{s:+d}')]):,}" for s in (-1, 0, 1)),
                *(f"{int(d[(*k, f'missed_unsafe_shift{s:+d}')]):,}" for s in (-1, 0, 1)),
                *(f"{100 * d[(*k, f'recall_shift{s:+d}')]:.1f}" for s in (-1, 0, 1)),
            ]
            rows.append(" & ".join(cells) + " \\\\")
    header = [
        "& & & \\multicolumn{3}{c}{Unsafe} & \\multicolumn{3}{c}{Missed unsafe} & \\multicolumn{3}{c}{Recall (\\%)} \\\\",
        "\\cmidrule(lr){4-6}\\cmidrule(lr){7-9}\\cmidrule(lr){10-12}",
        "& $\\tau$ (ms) & Boundary (referred)" + " & $-1$ & 0 & $+1$" * 3 + " \\\\",
    ]
    return _tabular("lrr" + "r" * 9, header, rows)


