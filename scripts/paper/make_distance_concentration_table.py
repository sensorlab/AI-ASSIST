"""Supplementary table for Note S3: distance concentration and uniform against kernel weights (R2.10a).

Writes results/tables/distance_concentration.tex (two tabular bodies, after the markers "% geometry" and "% weights"),
from results/data/distance_concentration.csv and results/data/eles_uniform_weights.csv. The caption lives in the
manuscript; the generated block is inlined there between begin/end markers.

Run from the repository root:
    uv run python scripts/paper/make_distance_concentration_table.py
"""

from __future__ import annotations

from pathlib import Path
from typing import Final

import pandas as pd

PROJECT_DIR: Final[Path] = Path(__file__).resolve().parents[2]
DATA_DIR: Final[Path] = PROJECT_DIR / "results" / "data"
OUTPUT_PATH: Final[Path] = PROJECT_DIR / "results" / "tables" / "distance_concentration.tex"
NOTE: Final[str] = "% Generated by scripts/paper/make_distance_concentration_table.py -- do not edit by hand."


def _tabular(spec: str, header: list[str], rows: list[str]) -> str:
    return "\n".join(
        [f"\\begin{{tabular}}{{{spec}}}", "\\toprule", *header, "\\midrule", *rows, "\\bottomrule", "\\end{tabular}"]
    )


def geometry() -> str:
    d = pd.read_csv(DATA_DIR / "distance_concentration.csv").set_index(["dataset", "measure", "quantity"])["estimate"]

    def spread(ds: str, measure: str) -> str:
        if (ds, measure, "q50") not in d:
            return "--"
        return f"{d[ds, measure, 'q50']:.2f} ({d[ds, measure, 'q10']:.2f}, {d[ds, measure, 'q90']:.2f})"

    rows = [
        "States & " + " & ".join(f"{int(d[ds, 'features', 'n_states']):,}" for ds in ("ELES", "BUS39")) + " \\\\",
        "Distance dimensions & "
        + " & ".join(f"{int(d[ds, 'features', 'n_dimensions']):,}" for ds in ("ELES", "BUS39"))
        + " \\\\",
        "Relative contrast, all states & " + " & ".join(spread(ds, "rc_all") for ds in ("ELES", "BUS39")) + " \\\\",
        "\\quad columns permuted & " + " & ".join(spread(ds, "rc_all_null") for ds in ("ELES", "BUS39")) + " \\\\",
        "Relative contrast, topology pool & " + " & ".join(spread(ds, "rc_pool") for ds in ("ELES", "BUS39")) + " \\\\",
        "Principal components, 90/95/99\\% & "
        + " & ".join(
            "/".join(f"{int(d[ds, 'pca', f'components_{p}pct']):,}" for p in (90, 95, 99)) for ds in ("ELES", "BUS39")
        )
        + " \\\\",
        "$n_\\mathrm{eff}/n$, selected group & " + spread("ELES", "neff_fraction") + " & -- \\\\",
    ]
    return _tabular("lrr", ["& ELES & BUS39 \\\\"], rows)


def weights() -> str:
    d = pd.read_csv(DATA_DIR / "eles_uniform_weights.csv")
    d = d[d["resampling_unit"].isna() | (d["resampling_unit"] == "state")].set_index(["availability", "quantity"])[
        "estimate"
    ]
    arms = (
        ("retrospective", "kernel"),
        ("retrospective", "uniform"),
        ("causal_lag0", "kernel"),
        ("causal_lag0", "uniform"),
    )

    def row(label: str, quantity: str, fmt) -> str:
        return " & ".join([label, *(fmt(d[a, quantity.format(w=w)]) for a, w in arms)]) + " \\\\"

    ms = lambda x: f"{1000 * x:.1f}"  # noqa: E731
    pct = lambda x: f"{100 * x:.2f}"  # noqa: E731
    rows = [
        row("MAE (ms)", "mae_{w}", ms),
        row("Median absolute error (ms)", "abs_error_q50_{w}", ms),
        row("95th percentile (ms)", "abs_error_q95_{w}", ms),
        row("99th percentile (ms)", "abs_error_q99_{w}", ms),
        row("Critical generator identified (\\%)", "top1_{w}", pct),
        row("Referral load, \\qty{200}{\\ms} (\\%)", "referral_load_{w}_200ms", pct),
        row("Missed unsafe, \\qty{200}{\\ms}", "missed_unsafe_{w}_200ms", lambda x: f"{int(x):,}"),
        row("Referral load, \\qty{150}{\\ms} (\\%)", "referral_load_{w}_150ms", pct),
        row("Missed unsafe, \\qty{150}{\\ms}", "missed_unsafe_{w}_150ms", lambda x: f"{int(x):,}"),
    ]
    header = [
        "& \\multicolumn{2}{c}{Retrospective} & \\multicolumn{2}{c}{Causal} \\\\",
        "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}",
        "& Kernel & Uniform & Kernel & Uniform \\\\",
    ]
    return _tabular("lrrrr", header, rows)


def main() -> None:
    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(f"{NOTE}\n% geometry\n{geometry()}\n% weights\n{weights()}\n")
    print(OUTPUT_PATH.read_text())


if __name__ == "__main__":
    main()
